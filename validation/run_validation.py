"""Out-of-fold validation of the deployed HepatiQ model.

Generates 5-fold stratified out-of-fold (OOF) predictions -- the same CV
scheme ml/train.py used for model selection -- then reports ROC-AUC,
Brier, precision, recall and F1 with 95% bootstrap confidence intervals,
next to a naive class-prior baseline (predicts the training-fold
prevalence for every held-out patient; AUC = 0.5 by construction).

Why OOF instead of scoring the training predictions:
    predict_proba on the data the model was fit on is optimistically
    biased (the imputer, scaler and classifier all saw those patients).
    Refitting a fresh pipeline per fold -- imputer/scaler fit only on the
    fold's training patients -- gives an honest estimate of performance
    on unseen patients, with no preprocessing leakage.

Why a class-prior baseline instead of a clinical score:
    A real MELD benchmark needs bilirubin, INR and creatinine. The Mayo
    PBC dataset has bilirubin and protime, but no INR and no creatinine,
    so MELD cannot be computed from this data -- a "MELD" built from
    protime and a fixed creatinine would be a non-clinical construct
    wearing a clinical name. The class-prior baseline answers the
    question that actually matters for judging the model: does it beat
    "always guess the cohort prevalence"? (See docs/ROADMAP.md for the
    decision record.)

Run:
    python validation/run_validation.py
    (also works as: python -m validation.run_validation)

Output:  validation/report.md   (committed deliverable)
         summary printed to stdout
"""

import sys
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import (
    brier_score_loss,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedKFold

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "ml"))

from impute_pipeline import build_feature_frame  # noqa: E402
from validation.validate import bootstrap_ci  # noqa: E402

MODEL_PATH = REPO_ROOT / "models" / "model.pkl"
DATA_PATH = REPO_ROOT / "data" / "pbc_5yr_target.csv"
REPORT_PATH = REPO_ROOT / "validation" / "report.md"

N_FOLDS = 5
SEED = 42
N_BOOT = 1000
THRESHOLD = 0.5

METRICS = {
    "ROC-AUC": roc_auc_score,
    "Brier score (lower=better)": brier_score_loss,
    "Precision": lambda y, p: precision_score(y, p >= THRESHOLD, zero_division=0),
    "Recall": lambda y, p: recall_score(y, p >= THRESHOLD, zero_division=0),
    "F1": lambda y, p: f1_score(y, p >= THRESHOLD, zero_division=0),
}


def out_of_fold_predictions(features: pd.DataFrame, target: pd.Series):
    """Return (model_oof, prior_oof) probability arrays, one value per patient."""
    cv = StratifiedKFold(n_splits=N_FOLDS, shuffle=True, random_state=SEED)
    model_oof = np.zeros(len(target))
    prior_oof = np.zeros(len(target))
    for train_idx, test_idx in cv.split(features, target):
        pipe = joblib.load(MODEL_PATH)
        pipe.fit(features.iloc[train_idx], target.iloc[train_idx])
        model_oof[test_idx] = pipe.predict_proba(features.iloc[test_idx])[:, 1]
        prior_oof[test_idx] = float(target.iloc[train_idx].mean())
    return model_oof, prior_oof


def score(predictions: np.ndarray, target: np.ndarray) -> dict:
    out = {}
    for name, fn in METRICS.items():
        point = float(fn(target, predictions))
        lower, upper = bootstrap_ci(
            predictions, target,
            lambda labels, preds, _fn=fn: float(_fn(labels, preds)),
            n_boot=N_BOOT, seed=SEED,
        )
        out[name] = {"point": point, "lower": float(lower), "upper": float(upper)}
    return out


def fmt(result: dict) -> str:
    return f"{result['point']:.4f} [{result['lower']:.4f}, {result['upper']:.4f}]"


def build_report(model_scores: dict, prior_scores: dict, cohort: dict) -> str:
    rows = "\n".join(
        f"| {name} | {fmt(model_scores[name])} | {fmt(prior_scores[name])} |"
        for name in METRICS
    )
    return f"""# HepatiQ Validation Report

*Generated by `validation/run_validation.py` — fully deterministic (folds and bootstrap both seed {SEED}).*

## Cohort

- Patients: **{cohort['n']}** ({cohort['events']} severe events / {cohort['nonevents']} event-free)
- Features: {cohort['features']} (training columns; `time`/`status` excluded as leakage)

## Method

- **Out-of-fold predictions**: 5-fold stratified CV (seed {SEED}); a fresh
  `IterativeImputer -> StandardScaler -> Logistic Regression` pipeline is fit on
  4 folds and scores the 5th, so every patient is scored by a model that never
  saw them, and preprocessing is fit only on training folds (no leakage).
- **95% confidence intervals**: bootstrap ({N_BOOT} resamples, seed {SEED}).
- **Baseline**: class-prior predictor — predicts the training-fold prevalence
  for every held-out patient. AUC ≈ 0.5 by construction; its Brier score is the
  label variance, i.e. "how well could a constant guess do".
- **No clinical-score benchmark (MELD etc.)**: the dataset lacks creatinine and
  INR, so MELD is not computable here. Decision recorded in `docs/ROADMAP.md`.

## Results (OOF, n={cohort['n']})

| Metric | HepatiQ model | Class-prior baseline |
|---|---|---|
{rows}

## Reading this

- The model's ROC-AUC CI should sit clearly above 0.5 (the baseline's AUC);
  the Brier score should sit clearly below the baseline's.
- These OOF numbers, not the in-sample training metrics, are the honest
  generalization estimate for this cohort. Sample size (n={cohort['n']}) keeps
  every CI wide — treat them as indicative bounds, not precise values.
- Full fold-by-fold model-selection numbers remain in
  `models/training_metrics.json`.
"""


def main() -> None:
    df = pd.read_csv(DATA_PATH)
    features, _ids, target = build_feature_frame(df)

    model_oof, prior_oof = out_of_fold_predictions(features, target)
    y = target.to_numpy()

    model_scores = score(model_oof, y)
    prior_scores = score(prior_oof, y)

    cohort = {
        "n": len(y),
        "events": int(y.sum()),
        "nonevents": int((y == 0).sum()),
        "features": len(features.columns),
    }

    report = build_report(model_scores, prior_scores, cohort)
    REPORT_PATH.write_text(report, encoding="utf-8")

    print(f"OOF validation — n={cohort['n']} ({cohort['events']} events)")
    print(f"{'metric':30s} {'model':28s} baseline")
    for name in METRICS:
        print(f"{name:30s} {fmt(model_scores[name]):28s} {fmt(prior_scores[name])}")
    print(f"\nReport written to {REPORT_PATH}")


if __name__ == "__main__":
    main()
